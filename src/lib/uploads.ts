import "server-only";
import { randomBytes } from "crypto";
import { connectDB } from "./db";
import {
  StoredUpload, UPLOAD_FOLDERS, type UploadFolder,
  SiteSettings, PageContent, Service, TeamMember, PricingPlan,
} from "./models";

export const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;
/** Vercel Functions reject request bodies over 4.5 MB, so chunks stay well below that. */
export const MAX_CHUNK_BYTES = 3 * 1024 * 1024;
export const MAX_CHUNKS = Math.ceil(MAX_UPLOAD_BYTES / MAX_CHUNK_BYTES);

const EXT_BY_MIME: Record<string, string> = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/webp": "webp",
  "image/gif": "gif",
};
export const ALLOWED_MIME = Object.keys(EXT_BY_MIME);

export function isUploadFolder(v: unknown): v is UploadFolder {
  return typeof v === "string" && (UPLOAD_FOLDERS as readonly string[]).includes(v);
}

/** Detects the real image type from magic bytes. Returns null for anything unsupported. */
export function sniffImageType(buf: Buffer): string | null {
  if (buf.length < 12) return null;
  if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 && buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a) return "image/png";
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") return "image/webp";
  const gif = buf.toString("ascii", 0, 6);
  if (gif === "GIF87a" || gif === "GIF89a") return "image/gif";
  return null;
}

export type UploadError = { status: number; error: string };

/** Validates and persists an image buffer. Extension is derived from the sniffed type. */
export async function saveImageBuffer(
  buf: Buffer,
  folder: UploadFolder
): Promise<{ ok: true; url: string; filename: string; size: number; folder: UploadFolder } | ({ ok: false } & UploadError)> {
  if (buf.length === 0) return { ok: false, status: 400, error: "The file is empty." };
  if (buf.length > MAX_UPLOAD_BYTES) return { ok: false, status: 413, error: "The file exceeds the 8 MB limit." };
  // The bytes are authoritative: the declared Content-Type is never trusted.
  const mime = sniffImageType(buf);
  if (!mime) return { ok: false, status: 415, error: "Unsupported file. Upload a PNG, JPEG, WebP or GIF image." };
  const filename = `${Date.now()}-${randomBytes(8).toString("hex")}.${EXT_BY_MIME[mime]}`;
  await connectDB();
  await StoredUpload.create({ folder, filename, mimeType: mime, size: buf.length, data: buf });
  return { ok: true, url: `/api/uploads/${folder}/${filename}`, filename, size: buf.length, folder };
}

const FILENAME_RE = /^\d{10,16}-[a-f0-9]{16}\.(png|jpg|webp|gif)$/;

/** Strict filename validation: blocks traversal, separators and anything not generated by us. */
export function isValidStoredFilename(name: string) {
  if (!name || name.includes("..") || name.includes("/") || name.includes("\\") || name.includes("\0")) return false;
  return FILENAME_RE.test(name);
}

/** Parses a /api/uploads/{folder}/{filename} URL. Returns null for anything else (e.g. Unsplash). */
export function parseUploadUrl(url: unknown): { folder: UploadFolder; filename: string } | null {
  if (typeof url !== "string" || !url.startsWith("/api/uploads/")) return null;
  const rest = url.slice("/api/uploads/".length).split("?")[0];
  const parts = rest.split("/");
  if (parts.length !== 2) return null;
  const [folder, filename] = parts;
  if (!isUploadFolder(folder) || !isValidStoredFilename(filename)) return null;
  return { folder, filename };
}

function collectUploadUrls(value: unknown, out: Set<string>) {
  if (typeof value === "string") {
    if (value.startsWith("/api/uploads/")) out.add(value.split("?")[0]);
  } else if (Array.isArray(value)) {
    for (const v of value) collectUploadUrls(v, out);
  } else if (value && typeof value === "object" && !(value instanceof Date) && !Buffer.isBuffer(value)) {
    for (const v of Object.values(value)) collectUploadUrls(v, out);
  }
}

/** Every /api/uploads URL currently referenced by any content record. */
export async function getReferencedUploadUrls() {
  await connectDB();
  const out = new Set<string>();
  const [settings, pages, services, team, plans] = await Promise.all([
    SiteSettings.find().lean(),
    PageContent.find().lean(),
    Service.find().lean(),
    TeamMember.find().lean(),
    PricingPlan.find().lean(),
  ]);
  collectUploadUrls([settings, pages, services, team, plans], out);
  return out;
}

/**
 * Deletes a stored image only if it is ours, valid, and no longer referenced anywhere.
 * Call this AFTER the new content reference has been persisted. Caller must be authorized.
 */
export async function deleteUploadIfUnreferenced(url: unknown) {
  const parsed = parseUploadUrl(url);
  if (!parsed) return false; // External / legacy / malformed URLs are never deleted.
  const refs = await getReferencedUploadUrls();
  if (refs.has(`/api/uploads/${parsed.folder}/${parsed.filename}`)) return false;
  const res = await StoredUpload.deleteOne(parsed);
  return res.deletedCount === 1;
}

/** Deletes previous images that were replaced or removed by a content save. */
export async function cleanupReplacedUploads(before: unknown, after: unknown) {
  const prev = new Set<string>();
  const next = new Set<string>();
  collectUploadUrls(before, prev);
  collectUploadUrls(after, next);
  for (const url of prev) {
    if (!next.has(url)) {
      try {
        await deleteUploadIfUnreferenced(url);
      } catch (err) {
        console.error("Upload cleanup failed", url, (err as Error).message);
      }
    }
  }
}

/** Removes unreferenced uploads older than the grace period (abandoned uploads). */
export async function cleanupAbandonedUploads(graceHours = 24) {
  await connectDB();
  const refs = await getReferencedUploadUrls();
  const cutoff = new Date(Date.now() - graceHours * 3600 * 1000);
  const candidates = await StoredUpload.find({ createdAt: { $lt: cutoff } }).select("folder filename").lean();
  let deleted = 0;
  for (const c of candidates) {
    const url = `/api/uploads/${c.folder}/${c.filename}`;
    if (!refs.has(url)) {
      await StoredUpload.deleteOne({ _id: c._id });
      deleted++;
    }
  }
  return { scanned: candidates.length, deleted };
}
